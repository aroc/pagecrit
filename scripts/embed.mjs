// Builds site/embed/pagecrit.js, the in-page PageCrit behind pagecrit.dev's "Try it on this page":
// the extension's core, export and content scripts plus embed/host.js in place of the service
// worker. The extension itself stays build-free. Usage: npm run embed
import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '..');
export const output = path.join(root, 'site/embed/pagecrit.js');
export function bundle() {
  const read = file => readFileSync(path.join(root, file), 'utf8').trimEnd();
  return `/* PageCrit, in-page demo build for pagecrit.dev. Generated by npm run embed from extension/ and
   embed/host.js; edit those, not this file. Source: https://github.com/aroc/pagecrit (MIT). */
(function () {
const script = document.currentScript;
${read('extension/core.js')}
${read('extension/export.js')}
${read('embed/host.js')}
PageCritHost.fontUrl = new URL('../fonts/caveat-latin.woff2', script?.src || location.href).href;
function run() {
${read('extension/content.js')}
}
// Opens the review, or shows the one already open. Returns false when another PageCrit (the
// extension) is already reviewing this page.
globalThis.PageCrit = {
  open() {
    if (!globalThis.__pageCritSession && document.querySelector('[data-pagecrit-root]')) return false;
    run();
    return true;
  }
};
})();
`;
}
if (process.argv[1] === import.meta.filename) {
  mkdirSync(path.dirname(output), {recursive: true});
  writeFileSync(output, bundle());
  console.log('Wrote site/embed/pagecrit.js');
}
